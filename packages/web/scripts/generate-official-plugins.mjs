/**
 * Bundle the curated official plugins into the console.
 *
 * The console is offline-first: official plugin packages ship inside the build
 * instead of being fetched from a registry. Each entry is a zip of the plugin
 * directory (no dist/, no downloaded jars) plus its manifest, encoded as base64
 * in a generated TypeScript module. Run this after changing an official plugin.
 */

import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const repoRoot = resolve(packageRoot, "../..");
const config = JSON.parse(readFileSync(join(packageRoot, "official-plugins.json"), "utf-8"));
const output = join(packageRoot, "src/official-plugins.generated.ts");

const CRC_TABLE = (() => {
	const table = new Uint32Array(256);
	for (let index = 0; index < 256; index += 1) {
		let value = index;
		for (let bit = 0; bit < 8; bit += 1) value = value & 1 ? 0xedb88320 ^ (value >>> 1) : value >>> 1;
		table[index] = value >>> 0;
	}
	return table;
})();

function crc32(buffer) {
	let crc = 0xffffffff;
	for (const byte of buffer) crc = CRC_TABLE[(crc ^ byte) & 0xff] ^ (crc >>> 8);
	return (crc ^ 0xffffffff) >>> 0;
}

/** Stored-entry zip; deterministic and dependency-free. */
function buildZip(files) {
	const locals = [];
	const centrals = [];
	let offset = 0;
	for (const file of files) {
		const name = Buffer.from(file.name, "utf-8");
		const checksum = crc32(file.data);
		const local = Buffer.alloc(30 + name.length);
		local.writeUInt32LE(0x04034b50, 0);
		local.writeUInt16LE(20, 4);
		local.writeUInt16LE(0x0800, 6);
		local.writeUInt16LE(0, 8);
		local.writeUInt16LE(0, 10);
		local.writeUInt16LE(0x0021, 12);
		local.writeUInt32LE(checksum, 14);
		local.writeUInt32LE(file.data.length, 18);
		local.writeUInt32LE(file.data.length, 22);
		local.writeUInt16LE(name.length, 26);
		name.copy(local, 30);
		locals.push(Buffer.concat([local, file.data]));

		const central = Buffer.alloc(46 + name.length);
		central.writeUInt32LE(0x02014b50, 0);
		central.writeUInt16LE(20, 4);
		central.writeUInt16LE(20, 6);
		central.writeUInt16LE(0x0800, 8);
		central.writeUInt16LE(0, 10);
		central.writeUInt16LE(0, 12);
		central.writeUInt16LE(0x0021, 14);
		central.writeUInt32LE(checksum, 16);
		central.writeUInt32LE(file.data.length, 20);
		central.writeUInt32LE(file.data.length, 24);
		central.writeUInt16LE(name.length, 28);
		central.writeUInt32LE(offset, 42);
		name.copy(central, 46);
		centrals.push(central);

		offset += local.length + file.data.length;
	}
	const directory = Buffer.concat(centrals);
	const eocd = Buffer.alloc(22);
	eocd.writeUInt32LE(0x06054b50, 0);
	eocd.writeUInt16LE(files.length, 8);
	eocd.writeUInt16LE(files.length, 10);
	eocd.writeUInt32LE(directory.length, 12);
	eocd.writeUInt32LE(offset, 16);
	return Buffer.concat([...locals, directory, eocd]);
}

const JUNK = new Set([".DS_Store", ".git", "node_modules", "dist", "download"]);
const SKIP = new Set(["dist", "download", ".git", "node_modules"]);

function collect(root, directory = root) {
	const files = [];
	for (const entry of readdirSync(directory, { withFileTypes: true })) {
		if (JUNK.has(entry.name)) continue;
		const full = join(directory, entry.name);
		if (entry.isDirectory()) {
			if (SKIP.has(entry.name)) continue;
			files.push(...collect(root, full));
		} else if (entry.isFile()) {
			files.push({ name: relative(root, full).split(sep).join("/"), data: readFileSync(full) });
		}
	}
	return files.sort((left, right) => left.name.localeCompare(right.name));
}

const entries = [];
for (const pluginPath of config.plugins ?? []) {
	const root = resolve(repoRoot, pluginPath);
	const manifestPath = join(root, "plugin.json");
	if (!existsSync(manifestPath)) throw new Error(`missing plugin.json: ${manifestPath}`);
	const manifest = JSON.parse(readFileSync(manifestPath, "utf-8"));
	const files = collect(root);
	const zip = buildZip(files);
	entries.push({ manifest, packageBase64: zip.toString("base64"), sizeBytes: zip.length });
	console.log(`official plugin ${manifest.id}@${manifest.version}: ${files.length} files, ${(zip.length / 1024).toFixed(1)} KB`);
}

const body = entries
	.map(
		(entry) => `\t{
\t\t// Parsed at module load; stored as a string so the generated file keeps a
\t\t// stable shape instead of being reformatted by the linter on every build.
\t\tmanifest: JSON.parse(${JSON.stringify(JSON.stringify(entry.manifest))}),
\t\tpackageBase64: "${entry.packageBase64}",
\t\tsizeBytes: ${entry.sizeBytes},
\t},`,
	)
	.join("\n");

writeFileSync(
	output,
	`/**
 * Generated by scripts/generate-official-plugins.mjs. Do not edit.
 * Official plugin packages are bundled into the console build.
 */

export interface BundledOfficialPlugin {
\tmanifest: Record<string, unknown>;
\tpackageBase64: string;
\tsizeBytes: number;
}

export const OFFICIAL_PLUGINS: BundledOfficialPlugin[] = [
${body}
];
`,
);
console.log(`wrote ${relative(repoRoot, output)} (${entries.length} plugins)`);
